# Truth table for docs/broker/mint-tabichat-pki.sh — the roster, the include, and the add paths.
#   sh src/tools/test_mint_pki.sh        (exit 1 on any failure)
#
# WHAT THIS FILE IS FOR. The generator writes `acl-generated.conf` from scratch on every run, so any
# grant that is not in the roster and not in the include file is DELETED by the next regeneration —
# silently, with the run printing nothing wrong. That is the defect this closes, and every cell below
# is one half of a pair: the mechanism that keeps a grant, beside the face where a grant is lost.
#
# THE GUARD IS PINNED, not just respected: `docs/broker/mint-tabichat-pki.sh` refuses a whole mint
# over an existing ca.key, on purpose, because a CA re-mint invalidates every pinned client. The add
# paths are a new named subcommand, NOT a relaxed guard, so this file asserts the refusal still fires
# after the change AND that the CA key bytes are unchanged by an add run. A check that only proves the
# new path works has just made the old rule untested.
#
# EVERYTHING RUNS ON A THROWAWAY CA IN ONE mktemp DIR. Never a live PKI, never a broker, never /etc,
# never /root. The scratch CA is generated by the script under test and destroyed by the trap.
#
# SITE-AGNOSTIC: the fixtures use `seat-a`/`seat-b`/`handnick`-style names, never a real lane's nick,
# for the same reason broker-fixture.sh defaults to a neutral pair — a test that mints a real seat's
# name puts that name in a certificate subject on every machine that runs it.
set -u

REPO=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
MINT="$REPO/docs/broker/mint-tabichat-pki.sh"

failed=0; ran=0
ok()    { ran=$((ran + 1)); printf 'ok    %s\n' "$1"; }
bad()   { ran=$((ran + 1)); failed=$((failed + 1)); printf 'FAIL  %s: %s\n' "$1" "$2"; }
say()   { printf '\n== %s ==\n' "$1"; }
check() { if [ "$2" = "$3" ]; then ok "$1 (=$3)"; else bad "$1" "got '$2', want '$3'"; fi; }
contains() { case "$1" in *"$2"*) ok "$3";; *) bad "$3" "output lacks '$2'";; esac; }
lacks()    { case "$1" in *"$2"*) bad "$3" "output CONTAINS '$2'";; *) ok "$3";; esac; }
count()    { if [ -f "$2" ]; then grep -c "$1" "$2" || true; else echo 0; fi; }   # zero, never a crash

[ -f "$MINT" ] || { printf 'FAIL  no generator at %s\n' "$MINT"; exit 1; }
sh -n "$MINT" 2>/dev/null && ok "the generator parses under sh" || bad "the generator parses under sh" "syntax error"
bash -n "$MINT" 2>/dev/null && ok "and under bash, since an operator may run it either way" \
  || bad "the generator parses under bash" "syntax error"
command -v openssl >/dev/null 2>&1 || { printf 'FAIL  openssl is absent; every cell below would be a lie\n'; exit 1; }

SCR=$(mktemp -d "${TMPDIR:-/tmp}/mintpki-XXXXXX") || { printf 'no scratch dir\n' >&2; exit 1; }
cleanup() { [ -n "${KEEP_SCR:-}" ] || rm -rf "$SCR"; }
trap cleanup EXIT INT TERM

# The two tracked inputs, rebuilt here so the cells control them and NEVER edit the repo's copies.
ROSTER="$SCR/roster.txt"
SUPP="$SCR/supp.conf"
printf '# a fixture roster\nseat-a\nseat-b   # trailing comment, same line\n\nseat-c\n' > "$ROSTER"
printf 'user CN=operator\ntopic write chat/+/_ctl/#\n' > "$SUPP"

# run_mint <outdir> [nicks...]        — the include and roster above are always explicit
run_mint() {
  out=$1; shift
  TABICHAT_ROSTER="$ROSTER" TABICHAT_ACL_SUPPLEMENT="$SUPP" sh "$MINT" -o "$out" "$@"
}

say "A WHOLE MINT FROM THE ROSTER, AND THE SAME MINT FROM THE COMMAND LINE"
A="$SCR/cli"; B="$SCR/roster"
cliout=$(run_mint "$A" seat-a seat-b seat-c 2>&1); rc=$?
check "the explicit run succeeds (rc=0)" "$rc" "0"
contains "$cliout" "the roster at $ROSTER is NOT merged in" \
  "and it says out loud that an explicit list overrides the roster"
rostout=$(run_mint "$B" 2>&1); rc=$?
check "the no-argument run succeeds on the roster (rc=0)" "$rc" "0"
contains "$rostout" "3 from the tracked roster $ROSTER" \
  "and it names the roster as its source with a count"
if cmp -s "$A/acl-generated.conf" "$B/acl-generated.conf"; then
  ok "the two generated ACLs are byte-identical — a roster nick is not a second-class nick"
else
  bad "the two generated ACLs are byte-identical" "$(diff "$A/acl-generated.conf" "$B/acl-generated.conf" | head -6)"
fi
check "comments, blank lines and inline text from the roster produced exactly three seat blocks" \
  "$(count '^user CN=' "$A/acl-generated.conf")" "4"     # three seats + the included operator

say "THE PRECEDENCE FACE — an argument is never silently ignored"
P="$SCR/precede"
run_mint "$P" seat-a >/dev/null 2>&1
check "with one nick on the command line, only that nick is minted" "$(count '^user CN=seat-a$' "$P/acl-generated.conf")" "1"
check "and the roster is NOT merged in behind it (seat-b absent)" "$(count '^user CN=seat-b$' "$P/acl-generated.conf")" "0"

say "THE DEFECT BEING CLOSED — a hand-added line does not survive; an included one does"
# The hand edit, made in the installed file's shape: somebody appends a nick to the generated ACL.
printf '\nuser CN=handnick\ntopic readwrite chat/tabith/msg/handnick\n' >> "$A/acl-generated.conf"
check "the hand line is present before the regeneration" "$(count '^user CN=handnick$' "$A/acl-generated.conf")" "1"
H="$SCR/again"
run_mint "$H" seat-a seat-b seat-c >/dev/null 2>&1
check "NEGATIVE — after a regeneration the hand-added nick is GONE (this is the loss)" \
  "$(count '^user CN=handnick$' "$H/acl-generated.conf")" "0"
check "and the included non-seat grant is PRESENT (this is the mechanism that keeps it)" \
  "$(count '^user CN=operator$' "$H/acl-generated.conf")" "1"
check "with its one scoped write line and nothing else" \
  "$(count 'topic write chat/+/_ctl/#' "$H/acl-generated.conf")" "1"
contains "$(printf '%s\n' "$(sed -n '/SUPPLEMENTARY INCLUDE/,$p' "$H/acl-generated.conf")")" \
  "appended verbatim from $SUPP" "and the generated file names the file it came from"

say "AN EMPTY INCLUDE FILE — the grant goes with it, so the include is doing the work, not luck"
: > "$SCR/empty.conf"
E="$SCR/empty"
TABICHAT_ROSTER="$ROSTER" TABICHAT_ACL_SUPPLEMENT="$SCR/empty.conf" sh "$MINT" -o "$E" seat-a >/dev/null 2>&1
check "NEGATIVE — with the include emptied, operator is absent" "$(count '^user CN=operator$' "$E/acl-generated.conf")" "0"
noabs=$(TABICHAT_ROSTER="$ROSTER" TABICHAT_ACL_SUPPLEMENT="$SCR/absent.conf" sh "$MINT" -o "$SCR/absent" seat-a 2>&1); rc=$?
check "and the mint still completes when the include file does not exist (rc=0)" "$rc" "0"
contains "$noabs" "supplementary include: none" "announced, never silent"

say "THE ADD PATHS — one leaf against a CA that already exists"
D="$A"
before=$(sha256sum "$D/ca/ca.key" | cut -c1-12)      # structure only: a prefix, never the key
beforecrt=$(sha256sum "$D/ca/ca.crt" | cut -c1-12)
addout=$(run_mint "$D" add-nick newcomer 2>&1); rc=$?
check "add-nick succeeds against the existing CA (rc=0)" "$rc" "0"
contains "$addout" "signed against the CA already in" "and it names the CA it is signing against"
openssl verify -CAfile "$D/ca/ca.crt" "$D/clients/newcomer/cert.pem" >/dev/null 2>&1 \
  && ok "the new leaf CHAINS to the existing CA (openssl verify rc=0)" \
  || bad "the new leaf chains to the existing CA" "openssl verify refused it"
check "its subject is exactly one RDN, CN=newcomer" \
  "$(openssl x509 -in "$D/clients/newcomer/cert.pem" -noout -subject | sed 's/^subject=//;s/^ *//')" "CN=newcomer"
check "and its ACL block landed in the generated file" "$(count '^user CN=newcomer$' "$D/acl-generated.conf")" "1"
check "with the per-nick write grant under its own leaf" \
  "$(count '^topic write chat/tabith/_ctl/newcomer/#$' "$D/acl-generated.conf")" "1"
after=$(sha256sum "$D/ca/ca.key" | cut -c1-12)
check "the CA key bytes are UNCHANGED by the add run (sha256 prefix, structure only)" "$before" "$after"
aftercrt=$(sha256sum "$D/ca/ca.crt" | cut -c1-12)
check "and the CA certificate is byte-identical — no re-issue rode along with the add" "$beforecrt" "$aftercrt"

say "THE GUARD THAT MUST NOT HAVE MOVEMENT"
g=$(run_mint "$D" seat-a 2>&1); rc=$?
check "a whole mint over an existing ca.key still REFUSES (rc=1)" "$rc" "1"
contains "$g" "already exists" "and it still says why"
g2=$(run_mint "$D" add-nick newcomer 2>&1); rc=$?
check "re-running add-nick for a nick that already has a block succeeds (rc=0)" "$rc" "0"
check "and it did NOT duplicate the ACL block" "$(count '^user CN=newcomer$' "$D/acl-generated.conf")" "1"
contains "$g2" "so none was duplicated" "saying so out loud instead of silently appending a second block"
NODIR="$SCR/noca"
n=$(run_mint "$NODIR" add-nick orphan 2>&1); rc=$?
check "NEGATIVE — add-nick REFUSES when no CA exists in the target dir (rc=1)" "$rc" "1"
contains "$n" "signs against a CA that must already be" "naming what is missing"
check "and it minted nothing on the way out" "$(count '' "$NODIR/acl-generated.conf" 2>/dev/null | head -1)" "0"

say "add-leaf — a non-seat identity gets a leaf and NO seat block"
al=$(run_mint "$D" add-leaf operator 2>&1); rc=$?
check "add-leaf succeeds (rc=0)" "$rc" "0"
openssl verify -CAfile "$D/ca/ca.crt" "$D/clients/operator/cert.pem" >/dev/null 2>&1 \
  && ok "its leaf chains to the existing CA" \
  || bad "its leaf chains to the existing CA" "openssl verify refused it"
check "and it wrote NO per-nick ACL block (the grant comes from the include alone)" \
  "$(count '^topic readwrite chat/tabith/msg/operator$' "$D/acl-generated.conf")" "0"
check "so operator appears exactly once in the whole file" \
  "$(count '^user CN=operator$' "$D/acl-generated.conf")" "1"

say "AN ACL THAT NEVER CARRIED THE INCLUDE GETS IT ON THE ADD RUN"
# The shape an operator actually meets: a generated file from before the include existed, patched by
# hand on the host. Adding one nick to that file is the run that has to make the non-seat grant
# durable, or the fix ships and the installed copy stays missing it.
U="$SCR/uplift"
TABICHAT_ROSTER="$ROSTER" TABICHAT_ACL_SUPPLEMENT="$SCR/absent.conf" sh "$MINT" -o "$U" seat-a >/dev/null 2>&1
check "this mint had no include file, so operator is absent" "$(count '^user CN=operator$' "$U/acl-generated.conf")" "0"
run_mint "$U" add-nick seat-b >/dev/null 2>&1
check "and the add run, with the include present now, applied it" "$(count '^user CN=operator$' "$U/acl-generated.conf")" "1"
check "while the new nick's own block landed beside it" "$(count '^user CN=seat-b$' "$U/acl-generated.conf")" "1"
run_mint "$U" add-nick seat-c >/dev/null 2>&1
check "NEGATIVE — a later add run did NOT append the include a second time" \
  "$(count 'SUPPLEMENTARY INCLUDE, appended verbatim' "$U/acl-generated.conf")" "1"
check "so operator appears once in the file, not once per run" "$(count '^user CN=operator$' "$U/acl-generated.conf")" "1"

say "A NICK THE CLIENT WOULD SILENTLY ALTER IS REFUSED, WITH THE EXTENSION'S OWN NAME"
for badnick in 'seat.c' 'seat c' 'seat/c' ''; do
  o=$(run_mint "$SCR/bad" add-nick "$badnick" 2>&1); rc=$?
  check "refused with rc=2: '$badnick'" "$rc" "2"
  contains "$o" "sender-acl-inert" "naming the notice the client itself raises (src/extensions/tabichat/index.ts)"
done
printf '# a roster with a glob line and a real nick\n*\nseat-z\n' > "$SCR/globroster.txt"
gr=$(TABICHAT_ROSTER="$SCR/globroster.txt" TABICHAT_ACL_SUPPLEMENT="$SUPP" sh "$MINT" -o "$SCR/glob" 2>&1); rc=$?
check "NEGATIVE — a glob character in the roster is refused as a nick, not expanded into file names" "$rc" "2"
contains "$gr" "sender-acl-inert" "and it is named as the same class"

say "NO SECRET LEAVES THE SCRIPT — stdout is paths, subjects and dates"
s=$(run_mint "$SCR/secret" seat-a 2>&1)
lacks "$s" "PRIVATE KEY" "no key material in the output"
lacks "$s" "BEGIN" "and no PEM body either"
check "every private key written by the mint is checked (CA, broker leaf, client leaf)" \
  "$(find "$SCR/secret" \( -name '*.key' -o -name 'key.pem' \) | wc -l | tr -d ' ')" "3"
n0600=0; nbad=0
for k in $(find "$SCR/secret" \( -name '*.key' -o -name 'key.pem' \)); do
  m=$(ls -l "$k" | awk '{print $1}')
  n0600=$((n0600 + 1))
  [ "$m" = "-rw-------" ] || nbad=$((nbad + 1))
done
check "and all $n0600 of them are 0600" "$nbad" "0"
say "THE SHIPPED DEFAULTS — the repo's own roster and include parse and produce a complete ACL"
SD="$SCR/shipdefaults"
sd=$(sh "$MINT" -o "$SD" 2>&1); rc=$?
check "the default run uses docs/broker/roster.txt (rc=0)" "$rc" "0"
contains "$sd" "docs/broker/roster.txt" "naming the tracked roster it read"
contains "$sd" "supplementary include: $REPO/docs/broker/acl-supplementary.conf" \
  "and naming the tracked include with its line count"
check "so the shipped ACL carries the operator grant" \
  "$(count '^user CN=operator$' "$SD/acl-generated.conf")" "1"
# one seat block per roster nick, plus the one included non-seat identity
ship_nicks=$(sed -e 's/#.*//' "$REPO/docs/broker/roster.txt" | tr -d ' \t\r' | grep -v '^$' | grep -c '' || true)
ship_blocks=$(count '^user CN=' "$SD/acl-generated.conf")
if [ "$ship_blocks" = "$((ship_nicks + 1))" ]; then

  ok "roster nicks $ship_nicks + the included operator = $ship_blocks blocks"
else
  bad "roster nicks plus the included operator equals the block count" "nicks=$ship_nicks blocks=$ship_blocks"
fi

printf '\n%s\n' "$([ "$failed" -gt 0 ] && printf '%d FAILED of %d cells' "$failed" "$ran" || printf 'all %d mint cells pass' "$ran")"
[ "$failed" -gt 0 ] && exit 1
exit 0
